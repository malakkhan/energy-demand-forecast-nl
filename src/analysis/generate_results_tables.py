#!/usr/bin/env python3
"""Generate the per-fold ROCV LaTeX comparison tables (appendix).

Emits one longtable per metric (RMSE, MAPE, MAE, MASE, PCC) comparing all
baselines and CMAT variants under the leakage-fixed pipeline (13-month-step
ROCV, folds 0-9). Multi-seed models report mean±std over seeds {42, 123, 7};
best per row is bolded. CMAT-Full shows "---" until its ROCV results exist,
at which point rerunning this script fills the column automatically.

Usage (from repo root):
    .venv/bin/python3 src/analysis/generate_results_tables.py > tables.tex
"""

import json
import os
import sys
from datetime import date, timedelta

import numpy as np
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(REPO, "src", "models", "baselines", "results")
CR = os.path.join(REPO, "src", "models", "cmat", "results")

HORIZONS = [60, 120, 180]
FOLDS = list(range(10))


def csv_model(path):
    if not os.path.exists(path):
        return None
    df = pd.read_csv(path)
    return df[df["horizon_days"].isin(HORIZONS) & (df["fold"] <= 9)]


def naive_model(name):
    d = json.load(open(f"{R}/{name}/{name}_rocv.json"))
    rows = [r for r in d["results"].values()
            if r["horizon_days"] in HORIZONS and r["fold"] <= 9]
    return pd.DataFrame(rows)


ORIGINS = {r["fold"]: r["test_origin"]
           for r in json.load(open(f"{R}/naive_24h/naive_24h_rocv.json"))["results"].values()}

MONTH = ["", "Jan", "Feb", "Mar", "Apr", "May", "Jun",
         "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def period_label(fold, h):
    o = date.fromisoformat(ORIGINS[fold])
    e = o + timedelta(days=h)
    if o.year == e.year:
        return f"{MONTH[o.month]}~{o.day:02d} -- {MONTH[e.month]}~{e.day:02d}, {o.year}"
    return f"{MONTH[o.month]}~{o.day:02d}, {o.year} -- {MONTH[e.month]}~{e.day:02d}, {e.year}"


NAIVE24 = 'Na\\"ive-24h'
SNAIVE = 'S-Na\\"ive'

MODELS = [
    ("Seq2Seq", csv_model(f"{R}/rocv_results_ashtar_seq2seq.csv"), True),
    ("MLR", csv_model(f"{R}/rocv_results_van_de_sande_mlr.csv"), False),
    ("Prophet-LSTM", csv_model(f"{R}/rocv_results_van_de_sande_prophet_lstm.csv"), True),
    (NAIVE24, naive_model("naive_24h"), False),
    ("Drift", naive_model("drift"), False),
    (SNAIVE, naive_model("seasonal_naive"), False),
    ("CMAT-Tab", csv_model(f"{CR}/rocv_results_cmat_tab.csv"), True),
    ("CMAT-NTL", csv_model(f"{CR}/rocv_results_cmat_ntl.csv"), True),
    ("CMAT-Full", csv_model(f"{CR}/rocv_results_cmat_full.csv"), True),
]

# (column, caption label, short comment label, decimals)
METRICS = [
    ("rmse", "RMSE", "RMSE", 1),
    ("mape_pct", "MAPE (\\%)", "MAPE", 2),
    ("mae", "MAE", "MAE", 1),
    ("mase", "MASE", "MASE", 3),
    ("pcc", "PCC", "PCC", 4),
]

N_COLS = 2 + len(MODELS)
COLSPEC = "r l " + " ".join("r" * len(MODELS))


def cell_value(df, multi, metric, h, fold):
    sub = df[(df["horizon_days"] == h) & (df["fold"] == fold)]
    if len(sub) == 0:
        return None, None
    vals = sub[metric].astype(float).values
    if multi and len(vals) > 1:
        return float(np.mean(vals)), float(np.std(vals))
    return float(vals[0]), None


header_names = " & ".join(
    ["\\textbf{H (d)}", "\\textbf{Target Period}"]
    + ["\\textbf{" + name + "}" for name, _, _ in MODELS])
HEADER = header_names + " \\\\"

full_pending = MODELS[-1][1] is None or len(MODELS[-1][1]) == 0
pending_note = " CMAT-Full pending." if full_pending else ""

print(r"""\section{Experimental Results Full}
\label{sec:apx:fourth_app}
% Split baseline comparison tables (RMSE / MAPE / MAE / MASE / PCC), one per
% metric. All results under the leakage-fixed pipeline: 13-month-step ROCV
% (10 folds, origins cycling Jan--Oct), per-fold PCA, MSE point forecasting,
% no crisis flag. Multi-seed models (Seq2Seq, Prophet-LSTM, CMAT variants)
% report mean$\pm$std over seeds \{42, 123, 7\}; MLR and the na\"ive
% baselines are deterministic.
%
% Generated by src/analysis/generate_results_tables.py — do not hand-edit;
% rerun the script when new results (e.g.\ CMAT-Full) land.
%
% Preamble requirements:
%   \usepackage{booktabs}
%   \usepackage{longtable}
%
% Usage: place \footnotesize (or \scriptsize, given the column count)
% before including these tables.
""")

for metric, caption_label, short, dp in METRICS:
    tab_label = "tab:baseline_" + metric.replace("_pct", "")
    better_high = metric == "pcc"
    print("%" + "=" * 60)
    print("% Table: " + short)
    print("%" + "=" * 60)
    print("\\begin{longtable}{" + COLSPEC + "}")
    print("\\caption{Per-fold ROCV results --- " + caption_label
          + ". Best per row in \\textbf{bold}." + pending_note + "}")
    print("\\label{" + tab_label + "} \\\\")
    print()
    for head_end in ("\\endfirsthead", "\\endhead"):
        print("\\toprule")
        print(HEADER)
        print("\\midrule")
        print(head_end)
        print()
    print("\\midrule")
    print("\\multicolumn{" + str(N_COLS) + "}{r}{\\textit{Continued on next page}} \\\\")
    print("\\endfoot")
    print()
    print("\\bottomrule")
    print("\\endlastfoot")
    print()
    for hi, h in enumerate(HORIZONS):
        if hi:
            print("\\midrule")
        for fold in FOLDS:
            cells = []
            means = []
            for name, df, multi in MODELS:
                if df is None or len(df) == 0:
                    cells.append(("---", None))
                    means.append(None)
                    continue
                m, s = cell_value(df, multi, metric, h, fold)
                means.append(m)
                if m is None:
                    cells.append(("---", None))
                elif s is not None:
                    txt = f"{m:.{dp}f}" + "{\\scriptsize$\\pm$" + f"{s:.{dp}f}" + "}"
                    cells.append((txt, m))
                else:
                    cells.append((f"{m:.{dp}f}", m))
            valid = [m for m in means if m is not None]
            best = max(valid) if better_high else min(valid)
            out = []
            for (txt, m) in cells:
                if m is not None and m == best:
                    out.append("\\textbf{" + txt + "}")
                else:
                    out.append(txt)
            print(f"{h} & {period_label(fold, h)} & " + " & ".join(out) + " \\\\")
    print("\\end{longtable}")
    print()
    print()

print("\\clearpage")
