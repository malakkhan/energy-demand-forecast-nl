#!/usr/bin/env python3
"""Generate the per-fold ROCV LaTeX comparison tables (appendix).

Emits one longtable per metric (RMSE, MAPE, MAE, MASE, PCC) comparing all
baselines and CMAT variants under the leakage-fixed pipeline (13-month-step
ROCV, folds 0-9). Multi-seed models report mean±std over seeds {42, 123, 7};
best per row is bolded. CMAT-Full shows "---" until its ROCV results exist,
at which point rerunning this script fills the column automatically.

Usage (from repo root):
    .venv/bin/python3 src/analysis/generate_results_tables.py > tables.tex
"""

import json
import os
import sys
from datetime import date, timedelta

import numpy as np
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(REPO, "src", "models", "baselines", "results")
CR = os.path.join(REPO, "src", "models", "cmat", "results")

# h120 deferred from the study scope (2026-08-29): evaluated horizons are
# 60d and 180d; any banked h120 rows in the CSVs are simply not rendered.
HORIZONS = [60, 180]
FOLDS = list(range(10))


def csv_model(path):
    if not os.path.exists(path):
        return None
    df = pd.read_csv(path)
    return df[df["horizon_days"].isin(HORIZONS) & (df["fold"] <= 9)]


def naive_model(name):
    d = json.load(open(f"{R}/{name}/{name}_rocv.json"))
    rows = [r for r in d["results"].values()
            if r["horizon_days"] in HORIZONS and r["fold"] <= 9]
    return pd.DataFrame(rows)


ORIGINS = {r["fold"]: r["test_origin"]
           for r in json.load(open(f"{R}/naive_24h/naive_24h_rocv.json"))["results"].values()}

MONTH = ["", "Jan", "Feb", "Mar", "Apr", "May", "Jun",
         "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def period_label(fold, h):
    o = date.fromisoformat(ORIGINS[fold])
    e = o + timedelta(days=h)
    if o.year == e.year:
        return f"{MONTH[o.month]}~{o.day:02d} -- {MONTH[e.month]}~{e.day:02d}, {e.year}"
    return f"{MONTH[o.month]}~{o.day:02d}, {o.year} -- {MONTH[e.month]}~{e.day:02d}, {e.year}"


NAIVE24 = 'Na\\"ive-24h'
SNAIVE = 'S-Na\\"ive'

MODELS = [
    ("Drift", naive_model("drift"), False),
    (NAIVE24, naive_model("naive_24h"), False),
    (SNAIVE, naive_model("seasonal_naive"), False),
    ("MLR", csv_model(f"{R}/rocv_results_van_de_sande_mlr.csv"), False),
    ("Seq2Seq", csv_model(f"{R}/rocv_results_ashtar_seq2seq.csv"), True),
    ("Prophet-LSTM", csv_model(f"{R}/rocv_results_van_de_sande_prophet_lstm.csv"), True),
    ("CMAT-Tab", csv_model(f"{CR}/rocv_results_cmat_tab.csv"), True),
    ("CMAT-NTL", csv_model(f"{CR}/rocv_results_cmat_ntl.csv"), True),
    ("CMAT-Full", csv_model(f"{CR}/rocv_results_cmat_full.csv"), True),
]

# (column, caption label, short comment label, decimals)
# Decimals kept minimal so the 9-model table fits portrait text widths:
# seed-std greatly exceeds the rounding error in every case.
METRICS = [
    ("rmse", "RMSE", "RMSE", 0),
    ("mape_pct", "MAPE (\\%)", "MAPE", 1),
    ("mae", "MAE", "MAE", 0),
    ("mase", "MASE", "MASE", 2),
    ("pcc", "PCC", "PCC", 3),
]

N_COLS = 2 + len(MODELS)
COLSPEC = "r l " + " ".join("r" * len(MODELS))


def cell_value(df, multi, metric, h, fold):
    sub = df[(df["horizon_days"] == h) & (df["fold"] == fold)]
    if len(sub) == 0:
        return None, None
    vals = sub[metric].astype(float).values
    if multi and len(vals) > 1:
        return float(np.mean(vals)), float(np.std(vals))
    return float(vals[0]), None


header_names = " & ".join(
    ["\\textbf{H (d)}", "\\textbf{Target Period}"]
    + ["\\textbf{" + name + "}" for name, _, _ in MODELS])
HEADER = header_names + " \\\\"

full_pending = MODELS[-1][1] is None or len(MODELS[-1][1]) == 0
pending_note = " CMAT-Full pending." if full_pending else ""

print(r"""\section{Experimental Results Full}
\label{sec:apx:fourth_app}
% Split baseline comparison tables (RMSE / MAPE / MAE / MASE / PCC), one per
% metric. All results under the leakage-fixed pipeline: 13-month-step ROCV
% (10 folds, origins cycling Jan--Oct), per-fold PCA, MSE point forecasting,
% no crisis flag. Multi-seed models (Seq2Seq, Prophet-LSTM, CMAT variants)
% report mean$\pm$std over seeds \{42, 123, 7\}; MLR and the na\"ive
% baselines are deterministic.
%
% Generated by src/analysis/generate_results_tables.py — do not hand-edit;
% rerun the script when new results (e.g.\ CMAT-Full) land.
%
% Preamble requirements:
%   \usepackage{booktabs}
%   \usepackage{longtable}
%
% Sizing is self-contained (\small + tight \tabcolsep inside a group),
% so no font commands are needed at the include site.
""")

for metric, caption_label, short, dp in METRICS:
    tab_label = "tab:baseline_" + metric.replace("_pct", "")
    better_high = metric == "pcc"
    print("%" + "=" * 60)
    print("% Table: " + short)
    print("%" + "=" * 60)
    print("\\begingroup\\small\\setlength{\\tabcolsep}{2pt}"
          "\\renewcommand{\\arraystretch}{1.2}")
    print("\\begin{longtable}{" + COLSPEC + "}")
    print("\\caption{Per-fold ROCV results --- " + caption_label
          + ". Best per row in \\textbf{bold}." + pending_note + "}")
    print("\\label{" + tab_label + "} \\\\")
    print()
    for head_end in ("\\endfirsthead", "\\endhead"):
        print("\\toprule")
        print(HEADER)
        print("\\midrule")
        print(head_end)
        print()
    print("\\midrule")
    print("\\multicolumn{" + str(N_COLS) + "}{r}{\\textit{Continued on next page}} \\\\")
    print("\\endfoot")
    print()
    print("\\bottomrule")
    print("\\endlastfoot")
    print()
    for hi, h in enumerate(HORIZONS):
        if hi:
            print("\\midrule")
        for fold in FOLDS:
            cells = []
            means = []
            for name, df, multi in MODELS:
                if df is None or len(df) == 0:
                    cells.append(("---", None))
                    means.append(None)
                    continue
                m, s = cell_value(df, multi, metric, h, fold)
                means.append(m)
                if m is None:
                    cells.append(("---", None))
                elif s is not None:
                    txt = f"{m:.{dp}f}" + "{\\tiny$\\pm$" + f"{s:.{dp}f}" + "}"
                    cells.append((txt, m))
                else:
                    cells.append((f"{m:.{dp}f}", m))
            valid = [m for m in means if m is not None]
            best = max(valid) if better_high else min(valid)
            out = []
            for (txt, m) in cells:
                if m is not None and m == best:
                    out.append("\\textbf{" + txt + "}")
                else:
                    out.append(txt)
            print(f"{h} & {period_label(fold, h)} & " + " & ".join(out) + " \\\\")
    print("\\end{longtable}")
    print("\\endgroup")
    print()
    print()

# ── Win-count summary table ────────────────────────────────────────────
# Counts, per metric and horizon, the folds in which each model had the
# best value — the same comparison that drives the bolding above, so the
# two always agree. Ties (identical best values) credit every tied model.
win_counts = {name: {} for name, _, _ in MODELS}
for metric, _, _, _ in METRICS:
    better_high = metric == "pcc"
    for h in HORIZONS:
        for name, _, _ in MODELS:
            win_counts[name].setdefault((h, metric), 0)
        for fold in FOLDS:
            entries = []
            for name, df, multi in MODELS:
                m = None
                if df is not None and len(df) > 0:
                    m, _ = cell_value(df, multi, metric, h, fold)
                entries.append((name, m))
            valid = [m for _, m in entries if m is not None]
            if not valid:
                continue
            best = max(valid) if better_high else min(valid)
            for name, m in entries:
                if m is not None and m == best:
                    win_counts[name][(h, metric)] += 1

metric_shorts = [short for _, _, short, _ in METRICS]
n_win_cols = 1 + len(HORIZONS) * len(METRICS) + 1

print("%" + "=" * 60)
print("% Table: per-fold win counts")
print("%" + "=" * 60)
print("\\begingroup\\small\\setlength{\\tabcolsep}{4pt}")
print("\\begin{table}[h]")
print("\\centering")
print("\\caption{Number of per-fold wins per model, metric, and horizon: "
      "the count of folds (out of 10 per horizon) in which the model "
      "achieved the best value of the metric among all models, matching "
      "the bolded cells of the preceding tables. A model without a result "
      "for a fold cannot win it.}")
print("\\label{tab:model_wins}")
print("\\begin{tabular}{l " + "r " * (len(HORIZONS) * len(METRICS)) + "r}")
print("\\toprule")
print(" & " + " & ".join(
    "\\multicolumn{" + str(len(METRICS)) + "}{c}{\\textbf{H = " + str(h) + "d}}"
    for h in HORIZONS) + " & \\\\")
for i in range(len(HORIZONS)):
    lo = 2 + i * len(METRICS)
    hi = lo + len(METRICS) - 1
    print("\\cmidrule(lr){" + f"{lo}-{hi}" + "}", end=" ")
print()
print("\\textbf{Model} & "
      + " & ".join(metric_shorts * len(HORIZONS))
      + " & \\textbf{Total} \\\\")
print("\\midrule")
for name, _, _ in MODELS:
    counts = [win_counts[name][(h, metric)]
              for h in HORIZONS for metric, _, _, _ in METRICS]
    print(name + " & " + " & ".join(str(c) for c in counts)
          + " & " + str(sum(counts)) + " \\\\")
print("\\bottomrule")
print("\\end{tabular}")
print("\\end{table}")
print("\\endgroup")
print()
print("\\clearpage")
